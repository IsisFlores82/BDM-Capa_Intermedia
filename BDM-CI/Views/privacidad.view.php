    <h1>Política de Privacidad</h1>
    <p>
        En Miku Academy, nos comprometemos a proteger la privacidad de nuestros usuarios. Esta política de privacidad explica cómo recopilamos, usamos y protegemos tu información personal cuando visitas nuestro sitio web o utilizas nuestros servicios. 
    </p>

    <h2>1. Información que recopilamos</h2>
    <p>Recopilamos diferentes tipos de información para mejorar tu experiencia en nuestro sitio:</p>
    <ul>
        <li><strong>Información personal:</strong> Como tu nombre, correo electrónico, número de teléfono, y otra información que nos proporciones al registrarte o interactuar con el sitio.</li>
        <li><strong>Datos de uso:</strong> Incluyen información sobre cómo navegas por el sitio, tus interacciones y tus preferencias.</li>
        <li><strong>Datos de pago:</strong> Cuando realizas una compra, recopilamos la información necesaria para procesar el pago, como métodos de pago y montos.</li>
        <li><strong>Datos de terceros:</strong> Información que recibimos cuando te registras o interactúas a través de plataformas como Facebook.</li>
    </ul>

    <h2>2. Uso de la información</h2>
    <p>La información recopilada se utiliza para:</p>
    <ul>
        <li>Proveerte acceso a los cursos y funcionalidades de la plataforma.</li>
        <li>Personalizar tu experiencia y ofrecerte recomendaciones.</li>
        <li>Procesar pagos y transacciones seguras.</li>
        <li>Comunicarnos contigo para fines administrativos, promociones, o soporte técnico.</li>
        <li>Cumplir con nuestras obligaciones legales y garantizar la seguridad de nuestros usuarios.</li>
    </ul>

    <h2>3. Uso de datos de Facebook</h2>
    <p>Si eliges registrarte o interactuar con Miku Academy utilizando tu cuenta de Facebook, podemos recopilar y usar ciertos datos proporcionados por esta plataforma:</p>
    <ul>
        <li>Nombre y foto de perfil.</li>
        <li>Dirección de correo electrónico asociada a tu cuenta de Facebook.</li>
        <li>Otra información básica de perfil público según lo permita Facebook.</li>
    </ul>
    <p>
        Miku Academy no compartirá ni publicará en tu cuenta de Facebook sin tu consentimiento explícito. Puedes revocar nuestro acceso a tu cuenta de Facebook en cualquier momento desde la configuración de tu cuenta de Facebook.
    </p>

    <h2>4. Seguridad de los datos</h2>
    <p>
        Implementamos medidas de seguridad técnicas y organizativas para proteger tus datos personales contra el acceso no autorizado, la alteración, la divulgación o la destrucción. Aunque nos esforzamos por proteger tu información, no podemos garantizar la seguridad absoluta de los datos transmitidos a través de Internet.
    </p>

    <h2>5. Terceros</h2>
    <p>Podemos compartir tus datos personales con terceros solo en los siguientes casos:</p>
    <ul>
        <li>Para procesar pagos o cumplir con servicios específicos.</li>
        <li>Cuando la ley nos lo exija o para proteger nuestros derechos legales.</li>
        <li>Con plataformas asociadas, siempre que sea necesario para mejorar la experiencia de los usuarios.</li>
    </ul>

    <h2>6. Tus derechos</h2>
    <p>
        Tienes derecho a acceder, corregir, eliminar o limitar el uso de tus datos personales. Si deseas ejercer alguno de estos derechos, contáctanos a través de nuestro correo: <a href="mailto:soporte@mikuacademy.com">soporte@mikuacademy.com</a>.
    </p>

    <h2>7. Cambios a esta política</h2>
    <p>
        Miku Academy puede actualizar esta política de privacidad ocasionalmente. Te notificaremos sobre cualquier cambio importante publicándolo en nuestro sitio web y actualizando la fecha de "Última actualización" al final de este documento.
    </p>

